"""Builds assets/region.js: the visitor's country and currency, guessed from their browser's time zone.

Run again only to pick up time zone or currency changes:  python tools/build_region_map.py
Uses the time zone database from pytz and currency data from Babel. Nothing is looked up online
on the site; exchange rates live in data/pricing.json and the price editor updates them.
"""
import json
from pathlib import Path

import pytz
from babel.numbers import get_currency_name, get_territory_currencies

REPO = Path(__file__).resolve().parent.parent
ZONES = Path(pytz.__file__).parent / "zoneinfo"

# The major currencies: the ones the European Central Bank publishes daily rates for, plus the US dollar.
MAJOR = {
    "USD", "EUR", "AUD", "BRL", "CAD", "CHF", "CNY", "CZK", "DKK", "GBP", "HKD", "HUF", "IDR", "ILS", "INR",
    "ISK", "JPY", "KRW", "MXN", "MYR", "NOK", "NZD", "PHP", "PLN", "RON", "SEK", "SGD", "THB", "TRY", "ZAR",
}
# Currencies pegged to, or used alongside, a major one in their region.
TIED = {
    "BTN": "INR", "NPR": "INR",  # Bhutan, Nepal
    "LSL": "ZAR", "NAD": "ZAR", "SZL": "ZAR",  # Lesotho, Namibia, Eswatini
    "BND": "SGD", "MOP": "HKD",  # Brunei, Macau
    "XOF": "EUR", "XAF": "EUR", "KMF": "EUR", "CVE": "EUR", "BAM": "EUR", "XPF": "EUR", "STN": "EUR",
}

zone_country, country_zones = {}, {}
for line in (ZONES / "zone.tab").read_text(encoding="utf-8").splitlines():
    if line and not line.startswith("#"):
        code, _, zone = line.split("\t")[:3]
        zone_country[zone] = code
        country_zones.setdefault(code, []).append(zone)

# Old names, such as Asia/Calcutta, that some browsers still report.
for line in (ZONES / "tzdata.zi").read_text(encoding="utf-8").splitlines():
    if line.startswith("L "):
        _, target, alias = line.split()
        if alias not in zone_country and target in zone_country:
            zone_country[alias] = zone_country[target]


# Countries that adopted the euro after the installed currency data was published.
EURO_ADOPTERS = {"HR", "BG"}


def shown_currency(country):
    """The currency to show, and whether it's the country's own."""
    if country in EURO_ADOPTERS:
        return "EUR", True
    own = [c for c in get_territory_currencies(country) if c in MAJOR or c in TIED] or get_territory_currencies(country)
    own = own[0] if own else "USD"
    if own in MAJOR:
        return own, True
    if own in TIED:
        return TIED[own], False
    return ("EUR" if country_zones[country][0].startswith("Europe/") else "USD"), False


currency, local = {}, []
for country in sorted(country_zones):
    shown, is_own = shown_currency(country)
    if shown != "USD":
        currency[country] = shown
    if is_own:
        local.append(country)

names = {code: get_currency_name(code, count=2, locale="en") for code in sorted(MAJOR)}
names["USD"] = "US dollars"

compact = lambda value: json.dumps(value, separators=(",", ":"))
script = f"""// Generated by tools/build_region_map.py. Do not edit by hand.
// Guesses the visitor's country from their browser's time zone, without asking any outside service,
// and picks the currency to show them: their own if it's a major currency, otherwise one used in
// their region, otherwise US dollars. Exchange rates come from data/pricing.json.
const ZONE_COUNTRY = {compact(dict(sorted(zone_country.items())))};
const COUNTRY_CURRENCY = {compact(currency)};
const OWN_CURRENCY = {compact(local)};
const CURRENCY_NAMES = {compact(names)};

function visitorCountry() {{
  try {{
    return ZONE_COUNTRY[Intl.DateTimeFormat().resolvedOptions().timeZone] || "";
  }} catch (error) {{
    return "";
  }}
}}

// The share of the list price this visitor pays: 1 unless their country has regional prices.
function priceFactor(pricing) {{
  const regional = pricing.regional;
  if (!regional || !regional.countries || !regional.countries.includes(visitorCountry())) return 1;
  return regional.percent / 100;
}}

// How to show prices to this visitor: the currency, a converter from US dollars, a formatter and a note.
function localPricing(pricing) {{
  const country = visitorCountry();
  const rates = (pricing.exchange && pricing.exchange.rates) || {{}};
  let code = COUNTRY_CURRENCY[country] || "USD";
  if (code !== "USD" && !rates[code]) code = "USD";
  const rate = code === "USD" ? 1 : rates[code];
  const factor = priceFactor(pricing);
  const locale = country ? `en-${{country}}` : "en-US";
  let digits = 2;
  try {{
    digits = new Intl.NumberFormat("en", {{ style: "currency", currency: code }}).resolvedOptions().maximumFractionDigits;
  }} catch (error) {{}}

  // Converted prices are rounded up, never down, to amounts a person would quote:
  // two significant figures from 100, whole numbers from 10, and quarters below that.
  const up = (value, step) => Math.round(Math.ceil(value / step - 1e-9) * step * 100) / 100;
  const convert = (usd) => {{
    if (usd === null || usd === undefined) return usd;
    const value = usd * factor * rate;
    if (code === "USD") return Math.round(value * 100) / 100;
    if (value >= 100) return up(value, 10 ** (Math.floor(Math.log10(value)) - 1));
    if (value >= 10 || digits === 0) return up(value, 1);
    return up(value, 0.25);
  }};
  const format = (n) => {{
    const whole = Number.isInteger(Math.round(n * 100) / 100);
    const options = {{ style: "currency", currency: code, minimumFractionDigits: whole ? 0 : digits, maximumFractionDigits: whole ? 0 : digits }};
    try {{
      return new Intl.NumberFormat(locale, options).format(n);
    }} catch (error) {{
      return new Intl.NumberFormat("en-US", options).format(n);
    }}
  }};
  const name = CURRENCY_NAMES[code] || code;
  const note = OWN_CURRENCY.includes(country)
    ? `Prices are in ${{name}}.`
    : `Prices are in ${{name}}, and we can quote in your local currency.`;
  return {{ code, convert, format, note }};
}}
"""
(REPO / "assets" / "region.js").write_text(script, encoding="utf-8")
print(f"{len(zone_country)} time zones, {len(country_zones)} countries, {len(currency)} shown in a currency other than US dollars")
for code in ("IN", "NP", "SN", "RS", "NG", "AE", "BR", "DE", "BG", "GB", "US", "JP", "PK", "BD"):
    print(code, currency.get(code, "USD"), "own" if code in local else "")
